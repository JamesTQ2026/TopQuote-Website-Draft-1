# -*- coding: utf-8 -*-
"""Write Open Graph and Twitter card tags into every page's <head>.

Nothing here is composed: the title comes from the page's own <title>, the
description from its own meta description, the address from its own canonical,
and a post's date and author from the byline it displays. Where a post's meta
description is just its title repeated, the description is left out rather than
padded.

The share image is assets/og-default.jpg at 1200x630. To change it, overwrite
that one file at the same size; no page needs editing.

Posts awaiting Openwork approval are skipped, as in tools/schema.py: their URLs
redirect to /blog, so there is nothing to share. Re-run both scripts when a post
is approved.

Run from the repo root:  python -I tools/og-tags.py
"""
import io, os, re, glob, json, datetime

os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))

SITE = "https://www.top-quote.co.uk"
IMAGE = SITE + "/assets/og-default.jpg"
IMAGE_ALT = "A family together outdoors"
MARK = "<!-- share cards"
DRY = os.environ.get("DRY") == "1"

DATE_RE = re.compile(r'data-lucide="calendar"[^>]*></i>\s*([0-9]{1,2} [A-Z][a-z]+ [0-9]{4})')
BYLINE = re.compile(r'<div style="font-weight:700;font-size:15px;color:#fff;">([^<]+)</div>')


def one(s, pat):
    m = re.search(pat, s)
    return m.group(1) if m else None


def title_of(s):
    t = one(s, r'<title>([^<]*)</title>') or ''
    return re.sub(r'\s*\|\s*TopQuote\s*$', '', t).strip()


def esc(t):
    """The value goes inside a double-quoted attribute, so only the quote and
    the ampersand need handling; the entities already in the source stay."""
    return t.replace('&', '&amp;').replace('&amp;amp;', '&amp;').replace('&amp;#', '&#') \
            .replace('"', '&quot;')


pending = set()
for line in io.open('tools/pending-approval.txt', encoding='utf-8'):
    line = line.strip()
    if line and not line.startswith('#'):
        pending.add(line.split('#')[0].strip())

report = {'website': 0, 'article': 0, 'no_description': 0, 'pending': 0, 'skipped': []}

for fn in sorted(glob.glob('*.html')):
    if fn == 'Mega Menu Test.dc.html':
        report['skipped'].append(fn + ' (internal test page)')
        continue
    s = io.open(fn, encoding='utf-8', newline='').read()
    if MARK in s:
        report['skipped'].append(fn + ' (already carries them)')
        continue
    url = one(s, r'<link rel="canonical" href="([^"]+)"')
    if not url:
        report['skipped'].append(fn + ' (no canonical, so no og:url)')
        continue

    slug = url.rstrip('/').rsplit('/', 1)[-1]
    is_post = fn.startswith('blog-')
    if is_post and slug.replace('blog-', '', 1) in pending:
        report['pending'] += 1
        continue

    title = title_of(s)
    desc = one(s, r'<meta name="description" content="([^"]*)"') or ''
    # a description that only repeats the headline tells a reader nothing
    if desc.strip().lower() == title.strip().lower():
        desc = ''
        report['no_description'] += 1

    tags = [
        ('property', 'og:type', 'article' if is_post else 'website'),
        ('property', 'og:site_name', 'TopQuote'),
        ('property', 'og:locale', 'en_GB'),
        ('property', 'og:title', title),
        ('property', 'og:url', url),
        ('property', 'og:image', IMAGE),
        ('property', 'og:image:width', '1200'),
        ('property', 'og:image:height', '630'),
        ('property', 'og:image:alt', IMAGE_ALT),
        ('name', 'twitter:card', 'summary_large_image'),
        ('name', 'twitter:title', title),
        ('name', 'twitter:image', IMAGE),
    ]
    if desc:
        tags.insert(4, ('property', 'og:description', desc))
        tags.append(('name', 'twitter:description', desc))

    if is_post:
        m = DATE_RE.search(s)
        if m:
            iso = datetime.datetime.strptime(m.group(1).strip(), '%d %B %Y').strftime('%Y-%m-%d')
            tags.append(('property', 'article:published_time', iso))
        b = BYLINE.search(s)
        if b:
            tags.append(('property', 'article:author', b.group(1).strip()))
        report['article'] += 1
    else:
        report['website'] += 1

    eol = "\r\n" if "\r\n" in s else "\n"
    block = (MARK + " -- generated by tools/og-tags.py; the image is"
             " assets/og-default.jpg, overwrite it at 1200x630 to change it -->" + eol +
             eol.join('<meta %s="%s" content="%s">' % (a, k, esc(v)) for a, k, v in tags) + eol)
    assert s.count('</head>') == 1, fn
    if not DRY:
        io.open(fn, 'w', encoding='utf-8', newline='').write(s.replace('</head>', block + '</head>', 1))

print(("DRY RUN -- nothing written\n") if DRY else "")
print("pages tagged as website : %d" % report['website'])
print("posts tagged as article : %d" % report['article'])
print("description left out (it only repeated the title): %d" % report['no_description'])
print("left alone, pending Openwork approval: %d" % report['pending'])
for x in report['skipped']:
    print("  skipped: " + x)
