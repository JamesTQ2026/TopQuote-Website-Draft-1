"""guide-site.css = mobile-responsive.css for the imported guide pages.

The site stylesheet's phone rules include catch-alls (e.g. every inline grid -> one column) written for the
site's own pages. On the guides they would rearrange the approved design, which has its own phone layout.
So: every rule outside a max-width media query is kept as is; inside max-width queries only rules aimed at
the site chrome (header, footer, mobile menu, services menu, cookie banner, page root) are kept.

usage: py -X utf8 -I tools/build-guide-css.py   (reads mobile-responsive.css, writes guide-site.css)
"""
import io, re

CHROME = re.compile(r'^\s*(header|footer|\.tq-hdr|#mnav|\.mnav|#svcMenu|\.svc-|#tqCookie|\.tq-cookie|#cookie|\.cookie|'
                    r'html|body|\*|:root|\.tqmm|#tqmm|#mcall|div\[aria-label\*="Feefo"\]|feefo|a\.tq-blue|a\.tq-tel|\.rc-walk-phone|\.step-num)', re.I)


def blocks(css):
    """yield (prelude, body) for each top-level block; comments removed."""
    css = re.sub(r'/\*[\s\S]*?\*/', '', css)
    i, n = 0, len(css)
    while i < n:
        j = css.find('{', i)
        if j < 0:
            break
        depth, k = 1, j + 1
        while depth and k < n:
            if css[k] == '{': depth += 1
            elif css[k] == '}': depth -= 1
            k += 1
        yield css[i:j].strip(), css[j + 1:k - 1]
        i = k


def keep_chrome(body):
    out = []
    for pre, inner in blocks(body):
        if pre.startswith('@'):
            sub = keep_chrome(inner)
            if sub.strip():
                out.append('%s {\n%s\n}' % (pre, sub))
            continue
        sels = [s for s in pre.split(',') if s.strip()]
        if sels and all(CHROME.match(s) for s in sels):
            out.append('%s {%s}' % (pre, inner))
    return '\n'.join(out)


src = io.open('mobile-responsive.css', encoding='utf-8').read()
out = ['/* generated by tools/build-guide-css.py from mobile-responsive.css: do not edit */']
kept = dropped = 0
for pre, inner in blocks(src):
    if pre.startswith('@media') and 'max-width' in pre:
        sub = keep_chrome(inner)
        total = len(list(blocks(inner)))
        if sub.strip():
            out.append('%s {\n%s\n}' % (pre, sub))
        kept += sub.count('{'); dropped += max(0, total - sub.count('{'))
    else:
        out.append('%s {%s}' % (pre, inner))
# Guide-only phone tweaks James asked for (10 Nov 2026): hero badges line up on the left, and the
# author card stacks the big initial above the name (same rule as mobile-responsive.css 95).
out.append('''@media (max-width: 700px) {
  div[style*="margin-left:auto"]:has(> img[src*="platinum-trusted-service-award"]) { margin-left: 0 !important; }
  .tq-ac > div[style*="display:flex"] { flex-direction: column !important; gap: 18px !important; }
}''')
io.open('guide-site.css', 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('guide-site.css written; phone rules kept (chrome only): ~%d, dropped: ~%d' % (kept, dropped))
